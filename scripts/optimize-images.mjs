// Generate content-versioned, responsive WebP assets without changing originals.
import { readdir, readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve, relative } from 'node:path';
import sharp from 'sharp';

const root = resolve(import.meta.dirname, '..');
const output = resolve(root, 'assets/img/responsive');
await mkdir(output, { recursive: true });
async function walk(dir) {
  const files = [];
  for (const item of await readdir(dir, { withFileTypes: true })) {
    if (item.name === 'responsive') continue;
    const path = resolve(dir, item.name);
    if (item.isDirectory()) files.push(...await walk(path));
    else if (/\.(jpg|jpeg|webp)$/i.test(item.name)) files.push(path);
  }
  return files;
}
const manifest = {};
let originalBytes = 0, smallBytes = 0;
for (const path of [...await walk(resolve(root, 'assets/img')), ...await walk(resolve(root, 'data/eras'))].sort()) {
  const source = await readFile(path);
  const meta = await sharp(source).rotate().toBuffer({ resolveWithObject: true });
  const { width, height } = meta.info;
  const hash = createHash('sha256').update(source).update('webp-q82-v1').digest('hex').slice(0, 16);
  const variants = [];
  for (const size of [...new Set([480, 960, 1440].map(n => Math.min(n, width)))]) {
    const file = `assets/img/responsive/${hash}-${size}.webp`;
    try { await stat(resolve(root, file)); }
    catch { await sharp(source).rotate().resize({ width: size, withoutEnlargement: true }).webp({ quality: 82, effort: 5 }).toFile(resolve(root, file)); }
    let bytes = (await stat(resolve(root, file))).size;
    for (const quality of [76, 70, 64, 58, 50]) {
      if (bytes <= 250 * 1024) break;
      await sharp(source).rotate().resize({ width: size, withoutEnlargement: true }).webp({ quality, effort: 5 }).toFile(resolve(root, file));
      bytes = (await stat(resolve(root, file))).size;
    }
    if (bytes > 250 * 1024) throw new Error(`Photo cannot meet the responsive size budget: ${path}`);
    variants.push({ src: file, width: size, bytes });
  }
  manifest[relative(root, path).replaceAll('\\', '/')] = { width, height, variants };
  originalBytes += source.length; smallBytes += variants[0].bytes;
}
await writeFile(resolve(root, 'assets/js/image-manifest.js'), `// Generated by npm run optimize:images; keep original photos as the source.\nexport default ${JSON.stringify(manifest)};\n`);

// Static HTML gets responsive sources without waiting for JavaScript.
for (const name of (await readdir(root)).filter(name => name.endsWith('.html'))) {
  const path = resolve(root, name);
  let html = await readFile(path, 'utf8');
  html = html.replace(/<img\b[^>]*>/g, tag => {
    const source = /data-original-src="([^"]+)"/.exec(tag)?.[1] ?? /\bsrc="([^"]+)"/.exec(tag)?.[1];
    const image = manifest[source];
    if (!image) return tag.includes('assets/img/logo.png') && !/\bwidth=/.test(tag) ? tag.replace('<img ', '<img width="44" height="44" ') : tag;
    const hero = source === 'assets/img/site/img-0561.jpg';
    const sizes = hero ? '(max-width: 860px) 92vw, 44vw' : source.includes('/ig/') ? '(max-width: 760px) 82vw, 38vw' : '(max-width: 860px) 92vw, 60vw';
    tag = tag.replace(/\s(?:src|srcset|sizes|width|height|loading|fetchpriority|decoding|data-original-src)="[^"]*"/g, '');
    const variants = image.variants;
    return tag.replace('<img ', `<img data-original-src="${source}" src="${variants.at(-1).src}" srcset="${variants.map(v => `${v.src} ${v.width}w`).join(', ')}" sizes="${sizes}" width="${image.width}" height="${image.height}" decoding="async" ${hero ? 'fetchpriority="high"' : 'loading="lazy"'} `);
  });
  await writeFile(path, html);
}
console.log(JSON.stringify({ images: Object.keys(manifest).length, originalBytes, smallVariantBytes: smallBytes, reductionPercent: Math.round((1 - smallBytes / originalBytes) * 100) }));
